import type { NotificationTarget } from "@/lib/notifier";
import type { NotificationEvent } from "@/lib/notifier/types";

/**
 * סוגי העבודות בתור.
 *
 * הטיפוס בטבלה הוא מחרוזת ולא ספירה של Prisma, בכוונה: הוספת סוג עבודה
 * חדש (תמלול, OCR, גיבוי) לא אמורה לדרוש מיגרציה על טבלה שמכילה שורות
 * ממתינות. הקבועים כאן הם מקור האמת לערכים המותרים.
 */
export const JOB_TYPES = {
  notify: "SEND_NOTIFICATION",
  /** תמלול הקלטה קולית */
  transcribe: "TRANSCRIBE",
  /** חילוץ טקסט מתמונה או מ-PDF */
  extract: "EXTRACT",
  /** סימון פניות ללא תנועה כמוסלמות — רץ יומית ומתזמן את עצמו מחדש */
  escalate: "DAILY_ESCALATION",
  /** גיבוי בסיס הנתונים — רץ יומית ומתזמן את עצמו מחדש */
  backup: "DAILY_BACKUP",
  /** הכרעת גורלו של מייל נכנס, ובמסלול התקין גם פתיחת הטיוטה ממנו */
  emailIntake: "EMAIL_INTAKE",
  /** שליחת מייל התשובה על מייל נכנס שכבר הוכרע */
  emailReply: "EMAIL_REPLY",
} as const;

export type JobType = (typeof JOB_TYPES)[keyof typeof JOB_TYPES];

/**
 * נתיב הרצה בתור. שני נתיבים, ולא אחד.
 *
 * ההבטחה במייל הנכנס היא **תשובה תוך חמש דקות** (אפיון §2.6 שלב 4). העובד
 * מריץ עבודה אחת בכל רגע נתון, ולכן סבב שנפתח בעשרות ג'ובי `EXTRACT` של
 * הזנה מרוכזת — כל אחד עד שתי דקות — היה דוחק תשובה שממתינה בתור הרחק
 * מעבר לחמש הדקות, בלי שאיש יראה תקלה: שני הג'ובים תקינים, רק הסדר הרס את
 * ההבטחה. שני נתיבים בלתי-תלויים פותרים את זה בשני הכיוונים — גם תשובה
 * שנתקעה מול Gmail אינה מעכבת התראה ליועץ.
 */
export type JobLane = "mail" | "general";

/**
 * הסוגים שרצים בנתיב הדואר — **מקור האמת היחיד** לחלוקה לנתיבים.
 *
 * הרשימה מונה את נתיב הדואר, והנתיב הכללי מוגדר כ"כל השאר" ולא כרשימה
 * משלו. זה מכוון: סוג עבודה חדש שיתווסף מחר נופל אוטומטית לנתיב הכללי
 * ונלקח. שתי רשימות מפורשות היו מייצרות את הכשל השקט הגרוע ביותר בתור —
 * ג'וב שאף לולאה אינה תופסת, ולכן נשאר PENDING לנצח בלי שגיאה.
 */
export const MAIL_JOB_TYPES = [JOB_TYPES.emailIntake, JOB_TYPES.emailReply] as const;

/**
 * לאיזה נתיב שייך סוג עבודה. מקבל `string` ולא `JobType` כי בטבלה הסוג הוא
 * מחרוזת חופשית — שורה שנוצרה בגרסה אחרת חייבת לקבל תשובה גם היא.
 */
export function jobLaneOf(type: string): JobLane {
  return (MAIL_JOB_TYPES as readonly string[]).includes(type) ? "mail" : "general";
}

/**
 * מטען ג'וב השליחה — **מזהים בלבד, לא טקסט מנוסח.**
 *
 * הפיתוי הוא לשמור את ההודעה המוכנה, אבל אז כל תיקון נוסח מפספס את מה
 * שכבר בתור, והטקסט הופך למקור אמת שני לצד `he.ts`. עם מזהים בלבד הג'וב
 * קורא את המצב **בזמן השליחה** — כך קבלן שהוסר בינתיים לא מקבל הודעה,
 * ופנייה שנמחקה לא שולחת דבר.
 */
export interface NotifyJobPayload {
  event: NotificationEvent;
  assignmentId: string;
  /** טקסט השאלה שנשאלה, או ההודעה שנכתבה בשרשור */
  note?: string;
  /**
   * יעד מפורש, ל-`MESSAGE` בלבד — הודעה בשרשור הולכת לצד השני, ומי הצד
   * השני תלוי בכותב ולא באירוע.
   */
  target?: NotificationTarget;
  /**
   * מזהה המשתמש הפנימי שכתב, כשההודעה יוצאת **לנמענים**.
   *
   * מזהה ולא שם, לפי הכלל שלמעלה: השם נקרא בזמן השליחה. בכיוון ההפוך —
   * הודעה מנמען לפותח — אין צורך בשדה כלל, כי הכותב הוא בעל השיוך והשם
   * שלו נשלף ממנו ממילא.
   */
  actorUserId?: string;
}

/**
 * מטען שני ג'ובי הדואר — **מזהה השורה בלבד**, מאותו נימוק של `NotifyJobPayload`.
 *
 * כל השאר כתוב על שורת ה-`MailboxMessage`: מי שלח, מה התקבל, ומה הוכרע.
 * הג'וב קורא אותה בזמן הריצה, ולכן התשובה מתארת את הטיוטה **כפי שהיא ברגע
 * השליחה** ולא כפי שהייתה כשהג'וב נוצר — הבדל שנראה בכל טיוטה שנערכה בין
 * שני הרגעים, וכל עוד המטען הוא מזהה בלבד אין דרך לטעות בו.
 */
export interface EmailIntakeJobPayload {
  mailboxMessageId: string;
}

/** מזהה שורת ה-`MailboxMessage` **היוצאת** שיש לשלוח */
export interface EmailReplyJobPayload {
  mailboxMessageId: string;
}
