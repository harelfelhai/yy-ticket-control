import type { AiErrorKind, AiRequestError } from "@/lib/ai/gemini";

/**
 * מדיניות הדחייה של הודעה נכנסת — משותפת לכל ערוצי הקליטה.
 *
 * **כשל זמני לעולם אינו הכרעה.** כשל מול הספק (Gmail, Graph) או מול המחלץ
 * דוחה את ההודעה עם השהיה גדלה, והשורה נשארת ממתינה: "לא הצלחנו לקרוא" אינו
 * "התעלמנו". המספרים כאן הם ההבטחה לשולח (§2.6 שלב 4: מענה תוך חמש דקות)
 * מול העמידות לתקלה ארוכה אצל הספק, ולכן הם מקור אחד לכל הערוצים.
 */

const MINUTE_MS = 60_000;

/**
 * ההשהיות של דחיית הודעה, בדקות, לפי מספר הניסיונות שכבר נעשו. הערך
 * האחרון חוזר על עצמו עד `MAX_DEFER_ATTEMPTS`.
 */
export const DEFER_MINUTES = [1, 2, 5, 10, 20, 40, 60] as const;

/**
 * מאיזה ניסיון הדחייה מדווחת ל-Sentry כ-issue ולא כלוג.
 *
 * כאן הבקאוף כבר מתייצב על שעה, כלומר ההודעה נדחית מעל שעה ורבע ואין שום
 * סיכוי לקיים את ההבטחה של חמש הדקות (§2.6 שלב 4). **ההנחה הקודמת שנרשמה
 * כאן — ש-`email-intake-not-stuck` יתריע ממילא — שגויה:** ה-check סופר רק
 * שורות שבהן `nextAttemptAt` ריק או עבר, ושורה בלולאת דחייה נמצאת במצב
 * הזה שניות ספורות בכל שעה. אותו תנאי בדיוק מוציא אותה גם מסריקת התקועים
 * של הסבב. בלי הדיווח כאן אין בכל המערכת מי שרואה אותה.
 *
 * הדיווח הוא אירוע **אחד** להודעה (שוויון מדויק), ולכן אינו זקוק לחניקה.
 */
export const DEFER_ALARM_ATTEMPTS = 6;

/**
 * הגג: אחרי כך וכך דחיות ההודעה נעצרת, ולא נוצר לה ג׳וב נוסף.
 *
 * 24 ניסיונות הם כ-19 שעות (78 דקות לשש הראשונות, ואז שעה לכל אחד). זהו
 * שינוי מכוון מול "לנסות שוב לנצח": דחייה בלי גג יוצרת שורת `Job` חדשה
 * כל שעה לנצח, והשורה נשארת ממתינה לעד — בניגוד ל-invariant שלפיו לכל
 * הודעה יש בדיוק הכרעה אחת. העצירה **אינה הכרעה**: היא אומרת "לא הצלחנו
 * לקרוא", ומשאירה את התיקון לאדם שמקבל את ה-issue. בוואטסאפ הגג הזה גם
 * רחוק מאוד משבעת הימים שבהם מזהה המדיה תקף.
 */
export const MAX_DEFER_ATTEMPTS = 24;

/** ההשהיה לפני הניסיון הבא, לפי מספר הניסיונות שכבר נעשו */
export function deferDelayMs(attemptsSoFar: number): number {
  const minutes = DEFER_MINUTES[Math.min(Math.max(attemptsSoFar, 0), DEFER_MINUTES.length - 1)];
  return minutes * MINUTE_MS;
}

// ─────────────────────────────── החילוץ ───────────────────────────────

/** ההשהיה בין ניסיונות חילוץ — קצרה, כי התקציב כולו הוא ארבע דקות */
export const EXTRACTION_RETRY_MS = 30_000;

/**
 * התקציב לחילוץ, נמדד **מהגעת ההודעה** ולא מתחילת העיבוד: ההבטחה בשלב 4
 * של §2.6 היא חמש דקות מהגעה, והמענה עוד צריך להישלח אחרי זה.
 */
export const EXTRACTION_BUDGET_MS = 4 * MINUTE_MS;

/**
 * מינימום **קריאות למחלץ**, גם כשהתקציב כבר אזל.
 *
 * הודעה שנקלטה באיחור (סבב שנתקע, שרת שהיה למטה) מגיעה לחילוץ כשארבע הדקות
 * מאחוריה, ובלי הרצפה הזו תקלה רגעית אחת אצל הספק הייתה נרשמת מיד כהכרעה
 * "החילוץ אינו זמין" — הכרעה שאין ממנה חזרה.
 *
 * **נספרות דחיות החילוץ בלבד**, ולא כל הדחיות של ההודעה: שתי דחיות מול
 * הספק היו שוחקות את הרצפה עד אפס — כלומר הכרעה סופית אחרי קריאה אחת
 * למחלץ, בדיוק במקרה שהרצפה נכתבה בשבילו.
 */
export const MIN_EXTRACTION_ATTEMPTS = 2;

/**
 * **הקו החד של EM-11:** האם כשל של המחלץ נדחה לניסיון נוסף, או הופך להכרעה
 * "החילוץ אינו זמין". `extractionAttempts` כולל את הקריאה שנכשלה עכשיו.
 *
 * - **זמני או מכסה** — נדחה כל עוד יש תקציב, או כל עוד לא נעשו שני ניסיונות.
 * - **תשובה פגומה** (`malformed`: לא JSON, או לא בסכימה) — ניסיון **אחד** נוסף,
 *   בלי קשר לתקציב, ואז הכרעה (§7 שורה 114). הפלט של המודל משתנה בין קריאות,
 *   ולכן תשובה פגומה יכולה להיות מקרית; אבל שינוי מבנה אצל הספק חוזר בכל
 *   קריאה, וניסיונות עד סוף התקציב היו רק מכפילים קריאות ומעכבים כל דיווח.
 * - **קבוע** (4xx, קלט גדול מדי) ו**הרשאה** — ישר להכרעה: אין מה לנסות שוב.
 */
export function shouldRetryExtraction(input: {
  kind: AiErrorKind;
  now: Date;
  receivedAt: Date;
  extractionAttempts: number;
}): boolean {
  if (input.kind === "malformed") return input.extractionAttempts < MIN_EXTRACTION_ATTEMPTS;
  const retryable = input.kind === "transient" || input.kind === "quota";
  const inBudget =
    input.now.getTime() + EXTRACTION_RETRY_MS < input.receivedAt.getTime() + EXTRACTION_BUDGET_MS;
  return retryable && (inBudget || input.extractionAttempts < MIN_EXTRACTION_ATTEMPTS);
}

/**
 * מה נרשם על ההודעה (`detail`) כשהוכרע "החילוץ אינו זמין" — **לאבחון בלבד**, לא
 * לשולח. בלעדיו הסיבה הייתה רק בלוג, שבסביבת פיתוח אינו נשמר כלל, והכרעה סופית
 * הייתה נשארת בלי הסבר (ריצה חיה של W7, 6.10.2026). `null` — אין מחלץ בסביבה.
 */
export function extractionUnavailableDetail(error: AiRequestError | null): string {
  const reason = error ? `${error.kind}: ${error.message}` : "אין מנוע חילוץ בסביבה";
  return `החילוץ אינו זמין — ${reason}`.slice(0, 1000);
}
