import { he } from "./he";

/**
 * מה לומר למנהל על מצב היידוע של נמען — פונקציה טהורה.
 *
 * הבחנה שהמערכת כולה נשענת עליה: **סטטוס השיוך אינו אומר שמישהו יודע.**
 * הוא אומר שהמערכת שייכה אותו, ומאז 1.1 הוא גם **נקרא** כך ("שויך") —
 * עד אז הוא אמר "נשלח", אותה מילה בדיוק שהשורה הזו מייצרת. פנייה שיושבת
 * יומיים כי לקבלן אין מייל ואיש לא לחץ על וואטסאפ תיראה בדיוק כמו פנייה
 * שנשלחה — אלא אם השורה הזו אומרת אחרת.
 *
 * הפונקציה טהורה ויושבת מחוץ לשכבת השירות כדי שתיבדק ישירות, בלי DB.
 */

export interface DeliveryFacts {
  /** מתי יצאה הודעה אוטומטית בפועל */
  notifiedAt: Date | null;
  /**
   * מתי המנהל פתח את הוואטסאפ עבור הנמען הזה.
   *
   * **אינו מסירה.** ‏`wa.me` פותח שיחה עם הטקסט מוכן, והשליחה היא לחיצה
   * נוספת באפליקציה שאין לנו גישה אליה. לכן הנוסח כאן אומר "נפתח" ולא
   * "נשלח" — ראה `he.ticket.waOpenedAt`.
   */
  waOpenedAt: Date | null;
  /**
   * מתי ההודעה האוטומטית לנמען הזה **הפסיקה לנסות**.
   *
   * נכתב בידי ה-worker כשג׳וב ההתראה מיצה את שלושת הניסיונות ונעל את עצמו
   * ל-`FAILED` (`src/jobs/queue.ts`), ומתאפס בשליחה שהצליחה. הוא קיים כדי
   * להבדיל בין "עוד לא יצא" ל"לא ייצא" — שני מצבים שנראו זהים לחלוטין עד
   * 1.1, מפני שהשורה הזו לא ידעה דבר על התור.
   */
  notifyFailedAt: Date | null;
  hasEmail: boolean;
  hasPhone: boolean;
  /** האם בכלל קיים ערוץ מייל בסביבה הזו (`isEmailConfigured`) */
  emailConfigured: boolean;
}

export function deliveryNote(facts: DeliveryFacts, formatTime: (value: Date) => string): string {
  if (facts.notifiedAt) return he.ticket.notifiedAt(formatTime(facts.notifiedAt));

  /**
   * הוואטסאפ נבדק **אחרי** המייל ולא לפניו.
   *
   * כשיצא מייל, הוא הערוץ שהמערכת יכולה להעיד עליו — היא ראתה את ה-SMTP
   * מקבל את ההודעה. פתיחת וואטסאפ היא עדות חלשה יותר (המנהל פתח; לא ידוע
   * אם שלח), ולכן היא אינה דוחקת אמירה חזקה ממנה. כשאין מייל היא האמירה
   * היחידה שיש — ובדיוק בשבילה השדה קיים.
   */
  if (facts.waOpenedAt) return he.ticket.waOpenedAt(formatTime(facts.waOpenedAt));

  /**
   * יש כתובת, וטרם יצאה הודעה — שתי סיבות שונות לחלוטין.
   *
   * ‏`notifyQueued` ("בתור לשליחה") נכון כשיש ערוץ: הג'וב ממתין או נכשל
   * ויחזור, ובשני המקרים אין מה לעשות. אבל כשאין ערוץ כלל הוא הבטחה
   * שלעולם לא תתקיים — מנהל שקורא אותה אינו מרים טלפון, והקבלן לא יוצא
   * לעבודה.
   *
   * הבדיקה **בתוך** הענף של `hasEmail` ולא לפניו, וזה תיקון של תיקון:
   * בגרסה הראשונה היא ישבה למעלה, וקבלן שאין לו מייל בכלל קיבל "ערוץ
   * המייל אינו מוגדר" במקום "אין מייל". שתי אמירות נכונות, אחת מהן אינה
   * הסיבה — ומי שקורא אותה מחפש הגדרה שחסרה במקום להשלים כתובת.
   */
  if (facts.hasEmail) {
    if (!facts.emailConfigured) return he.ticket.notifyNotConfigured;

    /**
     * **"בתור לשליחה" הבטיח דבר שכבר לא יקרה, וזה נמצא בפרודקשן.**
     *
     * הנוסח הקודם של הענף הזה נימק את עצמו ב"הג׳וב ממתין או נכשל **ויחזור**",
     * וזו הייתה הנחה שגויה: אחרי `MAX_ATTEMPTS` הג׳וב ננעל ל-`FAILED` ואינו
     * רץ שוב לעולם (`src/jobs/queue.ts`). כלומר השורה הזו הבטיחה שליחה
     * שלעולם לא תבוא — לנצח, בלי שום סימן.
     *
     * זה קרה: ב-7.9.2026 ארבעה ג׳ובים נכשלו סופית מפני ש-Railway חוסם SMTP
     * יוצא, והמסך המשיך לומר "ההודעה בתור לשליחה" לצד תג ירוק. מנהל שקורא
     * את זה ממתין; הקבלן אינו יודע דבר.
     *
     * הענף הזה הוא היחיד שדורש עובדה מחוץ ל-`Assignment` — ולכן היא נשמרת
     * **על** ה-`Assignment` (`notifyFailedAt`) ולא נשאלת מהתור: הפונקציה
     * נשארת טהורה, והמסך אינו צמוד למבנה ה-payload של הג׳וב.
     */
    if (facts.notifyFailedAt) {
      return facts.hasPhone
        ? he.ticket.notifyFailedWithPhone(formatTime(facts.notifyFailedAt))
        : he.ticket.notifyFailed(formatTime(facts.notifyFailedAt));
    }

    return he.ticket.notifyQueued;
  }

  // אין מייל אבל יש טלפון — זה בדיוק המצב שבו הכפתור שלצד השורה נחוץ.
  if (facts.hasPhone) return he.ticket.notifyNoEmail;

  // אין כלום. זו שגיאת נתונים שהמנהל היחיד שיכול לתקן, ולכן היא נאמרת
  // במפורש ולא נבלעת.
  return he.notices.cannotSendNoContact;
}
