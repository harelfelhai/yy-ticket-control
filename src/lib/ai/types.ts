/**
 * מנועי ה-AI: תמלול אודיו וחילוץ טקסט מתמונה או PDF.
 *
 * שניהם מוגדרים כחוזה ולא כקריאה ישירה לספק, מאותה סיבה שערוץ המייל
 * והאחסון מוגדרים כך: כדי שאפשר יהיה להריץ ולבדוק את כל המסלול בלי מפתחות
 * ובלי לשלם על כל ריצת בדיקות.
 *
 * **התוצר של שניהם הוא נגזרת ולא מקור.** ההקלטה והתמונה נשמרות תמיד; אם
 * העיבוד נכשל, הקובץ נשאר במקומו והמשתמש מקבל שורה שאומרת מה חסר. אין
 * מצב שבו כשל של ספק חיצוני גורם לאיבוד מה שאדם צילם או הקליט.
 */

export interface Transcriber {
  readonly name: string;
  /** מחזיר את הטקסט המתומלל, או מחרוזת ריקה כשלא נאמר דבר */
  transcribe(audio: Buffer, mimeType: string): Promise<string>;
}

export interface TextExtractor {
  readonly name: string;
  /** מחזיר את הטקסט שזוהה בקובץ, או מחרוזת ריקה כשאין טקסט */
  extract(file: Buffer, mimeType: string): Promise<string>;
}
