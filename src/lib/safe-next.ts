/**
 * אימות היעד שאליו מוחזר המשתמש אחרי התחברות (`?next=`).
 *
 * **למה זה מודול נפרד ולא תנאי inline.** הפרמטר מגיע מכתובת ה-URL, כלומר
 * מכל מי ששולח קישור. יעד שאינו מאומת הופך את מסך ההתחברות למנוע הפניות
 * לאתרים חיצוניים: קישור `‎/login?next=<יעד זר>` נראה לעובד כמו הדומיין של
 * החברה, הוא מתחבר — ונוחת אצל התוקף. זהו כלל אבטחה, ולכלל אבטחה מגיע בית
 * אחד שאפשר לבדוק אותו.
 *
 * **למה לא רשימת תווים אסורים.** הגרסה הקודמת בדקה
 * ‏`target.startsWith("/") && !target.startsWith("//")`, וזה נראה מספיק —
 * אבל `‎/\evil.com` עובר את שני התנאים. לפי מפרט WHATWG לוכסן הפוך מנורמל
 * ללוכסן קדימה בסכימות "מיוחדות" (http/https), ולכן הדפדפן פותר את זה
 * ל-`https://evil.com/`. כל רשימת איסור היא ניחוש של צורות הכתיבה שהדפדפן
 * מנרמל, וניחוש כזה מפספס בדיוק כשזה חשוב.
 *
 * הבדיקה כאן היא הפוכה: **פותרים את היעד בדיוק כמו שהדפדפן יפתור אותו**,
 * ומקבלים רק אם ה-origin לא זז. מה שהדפדפן רואה הוא מה שנבדק.
 */

/** ברירת המחדל: הלוח. מנהל עבודה שפותח את המערכת בבוקר רוצה להגיע לשם. */
export const DEFAULT_NEXT = "/board";

/**
 * בסיס פיקטיבי לפתרון היחסי. אינו נגזר מכתובת האפליקציה בכוונה: השאלה כאן
 * היא "האם היעד נשאר יחסי", ולא "לאיזה מארח". דומיין `.invalid` שמור לפי
 * ‏RFC 2606 ולעולם אינו נפתר ברשת.
 */
const PROBE_BASE = "https://resolve.invalid";

/**
 * מחזיר יעד יחסי בטוח, או `/board` כשהיעד חורג מהאפליקציה.
 *
 * מחזיר נתיב יחסי (ולא את הכתובת המלאה) כדי שההפניה תישאר יחסית גם אם
 * האפליקציה מוגשת מכמה מארחים.
 */
export function safeNextPath(target: string | null | undefined): string {
  if (!target) return DEFAULT_NEXT;

  try {
    const resolved = new URL(target, PROBE_BASE);
    // ‏origin שהשתנה פירושו שהיעד יצא מהאפליקציה — בלוכסן כפול, בלוכסן
    // הפוך, בסכימה מפורשת, או בכל צורה אחרת שהדפדפן מנרמל.
    if (resolved.origin !== PROBE_BASE) return DEFAULT_NEXT;

    return `${resolved.pathname}${resolved.search}${resolved.hash}`;
  } catch {
    // יעד שאינו ניתן לפענוח כלל אינו יעד.
    return DEFAULT_NEXT;
  }
}
