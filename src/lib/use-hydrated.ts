"use client";

import { useSyncExternalStore } from "react";

/**
 * מחזיר `false` עד שהרכיב עבר hydration בדפדפן.
 *
 * הבעיה שזה פותר: המסך מוגש כ-HTML מוכן ונראה אינטראקטיבי לחלוטין, אבל
 * מטפלי האירועים של React מחוברים רק כמה מאות מילישניות מאוחר יותר. לחיצה
 * בחלון הזה **נבלעת בשקט** — הכפתור נראה לחוץ ודבר לא קורה. ברשת סלולרית
 * באתר בנייה החלון הזה אינו זניח, ומנהל שלוחץ "הסר" ולא רואה שינוי מניח
 * שהמערכת שבורה.
 *
 * הפתרון: כפתור שתלוי ב-JavaScript מוצג מושבת עד ל-hydration. המשתמש רואה
 * שהוא עדיין לא זמין במקום ללחוץ לריק.
 *
 * שימו לב שטפסים שעובדים גם בלי JavaScript (כמו ההתחברות, שמשתמשת ב-
 * `action` של Server Action) **אינם** צריכים את זה — השבתתם הייתה שוברת
 * דווקא את המסלול שעובד תמיד.
 *
 * המימוש הוא `useSyncExternalStore` ולא `useState` + `useEffect`: זו
 * הצורה שבה React מבדיל בין תמונת מצב של השרת לזו של הלקוח, והיא אינה
 * מפעילה רינדור נוסף מיותר.
 */

/** אף פעם לא משתנה אחרי ה-hydration, ולכן אין למה להירשם */
const subscribe = () => () => {};

export function useHydrated(): boolean {
  return useSyncExternalStore(
    subscribe,
    () => true, // בדפדפן
    () => false, // בשרת ובמעבר ה-hydration הראשון
  );
}
