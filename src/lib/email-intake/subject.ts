/**
 * כלל הכותרת: מתי מייל חדש הוא בקשה לפתיחת פנייה (אפיון §2.6 שלב 1,
 * §5.ה3 כלל 1, §7 שורה 79).
 *
 * **אין כתובת ייעודית** — התיבה משותפת עם מערכות אחרות, והכותרת היא הסימן
 * היחיד. לכן הכלל כתוב כאן, בקוד, ולא כשאילתת `subject:` של Gmail: החיפוש
 * של Gmail מפרק מילים לפי כללים שאינם שלנו (אותיות שימוש, ניקוד), ומייל
 * שהוא לא החזיר פשוט לא היה מגיע לכאן — אובדן שקט. השאילתה מביאה את כל
 * המיילים מהשולחים המורשים, וההחלטה נעשית כאן.
 */

/**
 * תווים בלתי נראים שנכנסים לטקסט של מייל: שליטה בכיווניות (ALM, LRM/RLM,
 * embeddings, isolates), תווים ברוחב אפס (ZWSP, ZWNJ, ZWJ, word joiner, BOM),
 * מקף רך ו-CGJ.
 *
 * לקוחות דואר בעברית (Outlook בפרט) מוסיפים אותם לתחילת הכותרת, סביב מילה
 * או סביב מספר. הם בלתי נראים, ולכן כותרת שמתחילה ב-RLM ואחריו "תקלה" נראית
 * למשתמש בדיוק כמו "תקלה", ו"תקלה" עם ZWNJ באמצע נראית כמילה אחת — ואם לא
 * יוסרו, אף אחת מהן לא תזוהה.
 *
 * **המקור היחיד** לרשימה: `quote.ts` משתמש בה לזיהוי שורות ייחוס, והתאמת
 * השמות עוברת דרך `normalizeHebrew`.
 */
export const INVISIBLE_CHARS = /[\u00AD\u034F\u061C\u200B-\u200F\u202A-\u202E\u2060-\u2069\uFEFF]/g;

/**
 * ניקוד וטעמי מקרא: הסימנים המשולבים (combining) שבטווח U+0591–U+05C7.
 *
 * **ארבעה תווים בטווח אינם ניקוד אלא פיסוק** ונשארים: מקף (U+05BE), פסק
 * (U+05C0), סוף פסוק (U+05C3) ונון הפוכה (U+05C6). מחיקת המקף הייתה מדביקה
 * שתי מילים ("תקלה\u05BEחשמל" → "תקלהחשמל") ומפילה בדיוק את זיהוי גבול המילה
 * שהכלל הזה נשען עליו.
 */
const HEBREW_MARKS = /[\u0591-\u05BD\u05BF\u05C1\u05C2\u05C4\u05C5\u05C7]/g;

/**
 * הנרמול העברי של צינור המייל — **המקור היחיד** לו.
 *
 * כל מודול שמשווה טקסט שהגיע במייל לטקסט אחר (הכותרת כאן, קידומות של
 * תשובה אוטומטית, התאמת שמות לרשומות) עובר דרך הפונקציה הזו, כדי ששני
 * צדדים של השוואה לא ינורמלו בשני אופנים שונים.
 *
 * הסדר חשוב: NFKC קודם, כי הוא מפרק אותיות בצורת הצגה (U+FB1D–U+FB4F,
 * למשל U+FB2A, שין עם נקודה כתו יחיד) לאות + סימן ניקוד — ורק אחריו יש ניקוד להסיר.
 *
 * אינה נוגעת ברווחים, באותיות גדולות או בפיסוק: כל קורא צריך משהו אחר
 * (כלל הכותרת צריך את גבולות המילים כמות שהם, ההתאמה מכווצת רווחים).
 */
export function normalizeHebrew(text: string): string {
  return text.normalize("NFKC").replace(INVISIBLE_CHARS, "").replace(HEBREW_MARKS, "");
}

/**
 * "תקלה" או "תקלות" כמילה שלמה, עם עד שלוש אותיות שימוש (ו, ה, ב, כ, ל, מ, ש).
 *
 * גבול המילה נבדק מול אותיות עבריות בלבד, ולא ב-`\b`: ב-JavaScript `\b`
 * מכיר רק אותיות לטיניות, ולכן כל אות עברית נחשבת בו "לא-מילה" והוא לא
 * היה מבדיל בין "תקלה" ל"תקלהבה".
 *
 * **"תקלת" (סמיכות) אינה עונה** — הכלל מונה שתי צורות בדיוק (§7 שורה 79).
 * התוצאה: "תקלת חשמל" אינה נקלטת, ו"מתקלקל" או "תקלותיה" אינן נתפסות בטעות.
 *
 * הגבול של שלוש אותיות שימוש: האפיון מדגים אחת ושתיים ("התקלה", "לתקלות");
 * שלוש מכסות צירופים כמו "ולה-". רצף ארוך יותר נדיר בכותרת, ומרחיב את
 * ההתאמה לרצפי אותיות שאינם מילה.
 */
const INTAKE_WORD = /(?<![א-ת])[והבכלמש]{0,3}תקל(?:ה|ות)(?![א-ת])/;

/**
 * האם כותרת המייל מסמנת אותו כבקשה לפתיחת פנייה (EM-01).
 *
 * הכותרת מגיעה כבר מפוענחת מ-RFC 2047 (באחריות המתאם, `decodeRfc2047`). הקידומות
 * `RE:`/`Fwd:` אינן מוסרות: המילה נחפשת בכל מקום בכותרת, והן אינן מפריעות.
 * ההבחנה בין מייל חדש לתשובה אינה כאן — תשובה מזוהה לפי השרשרת (§5.ה3 כלל 2).
 */
export function isIntakeSubject(subject: string): boolean {
  return INTAKE_WORD.test(normalizeHebrew(subject));
}
