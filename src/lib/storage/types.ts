/** לאן הדפדפן שולח את הבתים, ועם אילו כותרות */
export interface UploadTarget {
  url: string;
  headers: Record<string, string>;
}

export interface MediaStorage {
  /** לזיהוי בלוגים ובבדיקות: מי בפועל מאחסן */
  readonly name: string;

  /** יעד העלאה חד-פעמי וקצר-מועד עבור מפתח שטרם קיים */
  createUploadTarget(key: string, contentType: string): Promise<UploadTarget>;

  /**
   * כתובת צפייה ישירה קצרת-מועד, או null.
   *
   * ‏null פירושו "אין כתובת ישירה — הגש את הבתים בעצמך". כך הדרייבר המקומי
   * אינו נדרש לחשוף קבצים בכתובת ציבורית, והבקשה ממשיכה לעבור דרך בדיקת
   * ההרשאה של האפליקציה.
   */
  createDownloadUrl(key: string): Promise<string | null>;

  /** קריאת הקובץ בשרת — נדרש לתמלול, לחילוץ טקסט ולהגשה מקומית */
  read(key: string): Promise<Buffer>;

  /**
   * מה באמת יושב באחסון תחת המפתח — או `null` אם כלום.
   *
   * ההעלאה נעשית ישירות מהדפדפן, ואישור ההעלאה מגיע מהלקוח — שעלול לשקר
   * או להיקטע. לפני שמסמנים `uploaded=true` מוודאים שהקובץ אכן נחת, אחרת
   * נוצרת רשומת מדיה שמצביעה על כלום. מפתח שאינו קיים → `null`; תקלת אחסון
   * אמיתית → זריקה (שתיתפס כשגיאה לא-צפויה, לא כ"חסר").
   *
   * **למה `head` ולא `exists` שמחזיר בוליאני.** הגודל שנבדק ברישום הוא
   * מספר שהלקוח **הצהיר** עליו, ובפרודקשן שום דבר לא מדד את הגודל האמיתי:
   * הכתובת החתומה של R2 נחתמת ללא אילוץ אורך, וה-route שכן מדד
   * (`api/media/upload/[...key]`) פועל רק באחסון מקומי. התוצאה היא
   * ש-`MAX_FILE_BYTES` לא היה נאכף כלל בפרודקשן, ו-`MediaFile.sizeBytes`
   * היה הצהרה ולא עובדה. ‏`HeadObject` ממילא מחזיר `ContentLength` —
   * הבוליאני פשוט זרק אותו.
   */
  head(key: string): Promise<{ sizeBytes: number } | null>;

  /** מחיקה. נדרשת לניקוי העלאה שנקטעה, ולא למחיקת מדיה של פנייה (Gate G5) */
  remove(key: string): Promise<void>;
}
