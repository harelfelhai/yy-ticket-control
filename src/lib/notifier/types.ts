/**
 * הטיפוסים של שכבת השליחה.
 *
 * הם מוגדרים בקובץ נפרד ובלי תלות ב-Prisma ובשום ספריית שליחה, כדי ששתי
 * המטרות של השכבה יתקיימו: הניסוח נבדק כפונקציה טהורה, והוספת ערוץ עתידי
 * (SMS, WhatsApp Business API) לא נוגעת בקוד שקורא לה.
 */

/**
 * האירועים שמצדיקים הודעה יוצאת. לא כל אירוע בשרשור שולח הודעה.
 *
 * ‏`MESSAGE` הוא היחיד שיעדו אינו נגזר מהאירוע אלא **מזהות הכותב** — ראה
 * `notificationTarget`. הוא נוסף כשהשרשור הפך לערוץ התקשורת היחיד: עד אז
 * הודעה בשרשור לא יידעה איש, והצד השני גילה אותה רק אם נכנס במקרה.
 */
export type NotificationEvent = "ASSIGNED" | "REOPENED" | "DONE" | "MESSAGE";

/** מה שצריך לדעת על הפנייה כדי לנסח הודעה עליה */
export interface TicketSummary {
  /** המספר הקריא לאדם — מה שאומרים בטלפון */
  seq: number;
  buildingName: string | null;
  apartmentNumber: string | null;
  domainName: string | null;
  description: string;
}

export interface ComposeInput {
  event: NotificationEvent;
  /** שם מקבל ההודעה */
  toName: string;
  /** מי גרם לאירוע — הקבלן ששאל או שסימן טופל. ריק בשיוך ובפתיחה מחדש. */
  actorName?: string;
  ticket: TicketSummary;
  /** לאן ההודעה מובילה: קישור קסם לקבלן, כתובת הפנייה למשתמש פנימי */
  link: string;
  /** תוכן חופשי שנלווה לאירוע — למשל טקסט השאלה שנשאלה */
  note?: string;
}

/**
 * ההודעה המנוסחת, לפני שהיא נכנסת לערוץ כלשהו.
 * `body` הוא טקסט פשוט: וואטסאפ אינו יודע HTML, והמייל עוטף את אותו טקסט.
 */
export interface ComposedMessage {
  subject: string;
  body: string;
}

export interface EmailMessage {
  to: string;
  subject: string;
  text: string;
  html: string;
  /**
   * המזהה שההודעה תצא בו (`Message-ID`).
   *
   * נמסר כדי שהמערכת תדע **מראש** במה לחפש: תשובה של השולח תחזור עם
   * `In-Reply-To` שמצביע על המזהה הזה, וזו הדרך לקשור אותה לטיוטה שהיא
   * עונה לה (EM-14). בלעדיו nodemailer מייצר מזהה אקראי, שאיש אינו רואה
   * ואיש אינו שומר — והתשובה נראית כמייל חדש.
   *
   * כאן, וכן ב-`inReplyTo` וב-`references`, המזהה **מנורמל**: בלי סוגריים
   * משולשים, כמו שהוא נשמר במסד. ההמרה לצורת הכותרת נעשית במקום אחד
   * (`formatMessageId`), כדי שלא יהיו שתי צורות לאותו מזהה.
   */
  messageId?: string;
  /** המזהה של ההודעה שעליה עונים — מה שמציב את התשובה בשרשור אצל השולח */
  inReplyTo?: string;
  /**
   * שרשרת המזהים שקדמו, לפי הסדר. לקוחות דואר בונים ממנה את העץ כשה-
   * `In-Reply-To` לבדו אינו מספיק (הודעה שהגיעה אחרי שהקודמת נמחקה).
   */
  references?: string[];
  /**
   * שרשור של Gmail, ולא של התקן.
   *
   * `In-Reply-To` מספיק ללקוח הדואר של הנמען, אבל **בתיבה שלנו** Gmail
   * מצרף הודעה יוצאת לשרשור קיים רק כשהבקשה נושאת את `threadId` שלו.
   * בלעדיו התשובה נראית בתיבה כשיחה חדשה, ומי שפותח את התיבה אינו רואה
   * את הפנייה ואת המענה עליה יחד. בערוץ SMTP אין לשדה מובן, והוא מתעלם.
   */
  threadId?: string;
  /**
   * ההודעה היא מענה שהמערכת יצרה, ולא מכתב של אדם.
   *
   * מוסיף את הכותרות שמבקשות מהצד השני **לא לענות** — בלעדיהן "מחוץ
   * למשרד" של הנמען עונה למענה שלנו, המערכת קולטת את התשובה, עונה עליה,
   * וכך הלאה. אותן כותרות הן גם מה ש-`autoReplySignal` מזהה בכיוון הנכנס,
   * ולכן הן גם מה שיעצור לולאה כזו אם היא בכל זאת תתחיל.
   */
  autoReply?: boolean;
}

/**
 * מה שהערוץ יודע לספר על ההודעה שיצאה. כל השדות אופציונליים: ערוץ שאינו
 * יודע אינו מנחש, והקורא מבחין בין "אין מידע" לבין ערך שגוי.
 */
export interface EmailSendResult {
  /** מזהה ההודעה אצל הספק (ב-Gmail: `Message.id`), לא מזהה RFC */
  id?: string;
  /** השרשור שאליו ההודעה צורפה **בפועל** */
  threadId?: string;
  /**
   * ה-`Message-ID` שיצא בפועל, כשהערוץ יודע לדווח עליו.
   *
   * לא בהכרח מה שנמסר ב-`EmailMessage.messageId`: Gmail רשאי לכתוב מזהה
   * משלו, ומי ששומר את מה שביקש במקום את מה שיצא לא ימצא את התשובה.
   *
   * **מנורמל**, כמו `EmailMessage.messageId` וכמו מה שהצד הנכנס שומר: בלי
   * סוגריים משולשים. ערוץ שמדווח את ערך הכותרת (וכך עושה nodemailer) מנרמל
   * לפני שהוא מחזיר — אחרת יש לאותו מזהה שתי צורות, וההשוואה מול
   * ה-`In-Reply-To` של התשובה נכשלת בשקט.
   */
  messageId?: string;
}

/**
 * ערוץ מייל אחד. המימוש האמיתי (Resend) והמימוש שרק כותב ללוג מקיימים את
 * אותו חוזה, ולכן אפשר להריץ את כל צינור השליחה בפיתוח ובבדיקות בלי מפתח
 * ובלי לשלוח מייל לאיש.
 */
export interface EmailTransport {
  /** לזיהוי בלוגים ובבדיקות: מה בפועל שלח את ההודעה */
  readonly name: string;
  /**
   * הערוץ מדמה שליחה ואינו מוציא דואר לאיש.
   *
   * הדגל קיים כדי ש**שכבת השליחה תדע** שלא יצא כלום, ולא רק שהקריאה לא
   * זרקה. בלעדיו `sendNotification` סימנה `notifiedAt` גם על ערוץ הקונסולה,
   * והמסך הכריז "נשלח ב-…" על מייל שמעולם לא נשלח — בדיוק התקלה השקטה
   * שהמערכת הזו נבנתה כדי למנוע.
   */
  readonly simulated?: boolean;
  /**
   * מחזיר את מה שהערוץ **יודע** על ההודעה שיצאה, ולא void.
   *
   * הסיבה היא EM-14: הקישור בין תשובה שתגיע מחר לבין הטיוטה שהיא עונה לה
   * נשען על מזהים שרק הערוץ רואה — Gmail עונה במזהה ההודעה ובשרשור שאליו
   * צורפה, ואלה בדיוק מה שצריך להישמר. ערוץ שאינו יודע מחזיר `{}`.
   */
  send(message: EmailMessage): Promise<EmailSendResult>;
}
