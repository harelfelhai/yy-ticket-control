"use client";

import type { ReactNode } from "react";
import { cardClasses } from "@/components/ui/card";

/**
 * כרטיס רשומה לחיץ ברשימת ניהול — מקור אמת אחד לשלושת המסכים (0.7).
 *
 * **מה שהשתנה ולמה.** עד 0.7 כל שורה ברשימות הניהול נשאה את הפרטים
 * **ואת הפעולות**: שם, מטא-דאטה, ואז "בניינים ודירות" · "שנה שם" · "מחק",
 * או "ערוך פרטים" · "השבת". התוצאה היא שרשימה שסורקים בה נקראת כטופס —
 * שלושה פקדים גלויים בכל שורה מתחרים על תשומת הלב עם המידע שהם פועלים
 * עליו, וככל שיש יותר רשומות כך הרעש גדל ליניארית.
 *
 * ההכרעה: **הכרטיס מסכם, הדיאלוג מפרט.** הכרטיס מחזיק את מה שמזהה את
 * הרשומה בסריקה, והפעולות יורדות לדיאלוג שנפתח בלחיצה עליו.
 *
 * **‏`<button>` על כל שטח הכרטיס, ולא כפתור בפינה** — § אזורי מגע:
 * "כרטיס לחיץ = יעד אחד על כל השטח". זה גם מה שמאפשר לוותר על רצפת גובה
 * מפורשת: הכרטיס נושא `p-3` ותוכן בן שתי שורות, כלומר הוא רחוק מעל גובה
 * הפקד ממילא.
 *
 * **אין כאן פקד מקונן, וזה תנאי ולא מקרה.** ‏`<button>` בתוך `<button>`
 * הוא HTML לא חוקי, וקישור בתוך כפתור לוכד את הלחיצה. כל הפעולות נמצאות
 * בדיאלוג, ולכן השאלה אינה עולה — אבל מי שיתפתה להחזיר "מחק" לפינת
 * הכרטיס ישבור את שניהם בבת אחת.
 *
 * **‏`text-start` חובה:** ‏`<button>` מיישר טקסט למרכז כברירת מחדל של
 * ה-UA, וכרטיס שתוכנו ממורכז נקרא כהודעה ולא כשורה ברשימה.
 */
export function RecordCard({
  label,
  onOpen,
  children,
}: {
  /**
   * השם הנגיש של הכרטיס — מה שקורא מסך מכריז עליו, ומה שבדיקה מאתרת בו.
   *
   * נדרש במפורש ואינו נגזר מהתוכן: תוכן הכרטיס הוא שם **ועוד** מטא-דאטה
   * (טלפון, תפקיד, מוני פניות), וצירוף הכול למחרוזת אחת נותן שם נגיש
   * באורך שורה שלמה — כלומר בורר שנשבר בכל שינוי תצוגה.
   */
  label: string;
  onOpen: () => void;
  children: ReactNode;
}) {
  return (
    <li>
      <button
        type="button"
        onClick={onOpen}
        aria-label={label}
        className={cardClasses("flex w-full flex-col gap-1 text-start")}
      >
        {children}
      </button>
    </li>
  );
}
