import { describe, expect, it } from "vitest";
import { he } from "@/lib/he";

/**
 * ‏`he.ticket.location` היא הצורה האחת שבה מיקום נכתב במערכת.
 *
 * היא נוצרה בדיעבד, אחרי שהבדיקה הידנית של מסך הבניינים חשפה שלכל מסך
 * שהציג מיקום היה ניסוח משלו — וכשמסך הניהול נזקק להבחין בין "דירה 1"
 * שבשני בניינים, הניסוח שנכתב שם מזיכרון יצא "דירה 1 בבניין בניין א".
 *
 * הבדיקות כאן מקבעות את שתי התכונות שבגללן היא קיימת: הפורמט האחיד,
 * והתנהגות מוגדרת כששדה חסר (טיוטה יכולה להישמר בלי מיקום מלא).
 */
describe("he.ticket.location — מיקום בצורה אחת", () => {
  it("מרכיב בניין ודירה בפורמט של כותרת הפנייה", () => {
    expect(he.ticket.location("בניין א", "3")).toBe("בניין א · דירה 3");
  });

  it("אינו מוסיף את המילה 'בניין' — הבניינים כבר נקראים כך", () => {
    // "דירה 3 בבניין בניין א" הוא בדיוק מה שהפורמט הזה נועד למנוע.
    expect(he.ticket.location("בניין א", "3")).not.toContain("בבניין");
  });

  it("בניין בלבד — בלי מפריד תלוי", () => {
    expect(he.ticket.location("בניין ב", null)).toBe("בניין ב");
  });

  it("דירה בלבד — כשהבניין טרם נבחר בטיוטה", () => {
    expect(he.ticket.location(null, "12")).toBe("דירה 12");
  });

  it("שני השדות חסרים — מחרוזת ריקה, כדי שהקורא יחליט מה להציג במקום", () => {
    // מחרוזת ריקה ולא "אין מיקום": מסך התגית מציג `he.ticket.noLocation`
    // ומסך הלוח מציג כלום. ההחלטה שייכת למסך, לא לפורמטר.
    expect(he.ticket.location(null, null)).toBe("");
    expect(he.ticket.location(undefined, undefined)).toBe("");
  });

  it("מספר דירה 0 אינו נבלע — הוא ערך ולא היעדר", () => {
    expect(he.ticket.location("בניין א", "0")).toBe("בניין א · דירה 0");
  });
});
