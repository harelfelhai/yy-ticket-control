import { describe, expect, it } from "vitest";
import { scan } from "../../unit/source-scan";

/**
 * WA-12 (§5.ה5 כלל 3, §7 שורה 100): **המערכת אינה משנה דבר בצ'אט ואינה מסמנת הודעות
 * כנקראו.** המספר העסקי רץ גם באפליקציה בטלפון (Coexistence), והצוות קורא שם את
 * השיחות — "נקרא" שהמערכת הייתה מסמנת היה מעלים מהם הודעות שעוד לא ראו. אותו עיקרון
 * כמו בתיבת המייל (EM-20), ונאכף באותה צורה: ביכולת, לא במשמעת.
 *
 * ב-Cloud API סימון כנקרא הוא בקשה לנקודת הקצה של השליחה עם `status: "read"`, וחיווי
 * הקלדה הוא `typing_indicator`. אף אחד מהם אינו קיים בקוד. **"read" כערך שמגיע מ-Meta
 * מותר** — זה מצב המסירה של הודעה שהמערכת שלחה (`wa-webhook.ts`, `delivery.ts`), ולא
 * פעולה על הודעה של מישהו אחר.
 */
describe("WA-12 — המערכת אינה מסמנת הודעות כנקראו ואינה משנה דבר בצ'אט", () => {
  it("אין בקשה עם status: \"read\" בשום מקום ב-src", () => {
    expect(scan(/status\s*:\s*["']read["']/)).toEqual([]);
  });

  it("אין חיווי הקלדה", () => {
    expect(scan(/typing_indicator/)).toEqual([]);
  });
});
